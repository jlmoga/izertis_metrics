const browserLang = navigator.language || navigator.userLanguage || '';
function detectLang(b) {
    if (b.startsWith('es')) return 'es';
    if (b.startsWith('en')) return 'en';
    return 'ca';
}
export let currentLang = localStorage.getItem('moga_lang') || detectLang(browserLang);

export const t = (key) => (translations[currentLang] && translations[currentLang][key]) ? translations[currentLang][key] : key;

export function setLang(lang) {
    currentLang = lang;
    localStorage.setItem('moga_lang', lang);
}

export function applyTranslations() {
    const tr = translations[currentLang];
    if (!tr) return;

    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (tr[key]) el.textContent = tr[key];
    });
    document.querySelectorAll('[data-i18n-title]').forEach(el => {
        const key = el.getAttribute('data-i18n-title');
        if (tr[key]) el.title = tr[key];
    });
    document.querySelectorAll('[data-i18n-aria]').forEach(el => {
        const key = el.getAttribute('data-i18n-aria');
        if (tr[key]) el.setAttribute('aria-label', tr[key]);
    });

    document.documentElement.lang = currentLang;
}
